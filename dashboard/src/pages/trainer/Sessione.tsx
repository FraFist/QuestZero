// Pagina di una sessione: codice di abbinamento finché il visore non si collega (RF-11),
// poi lo stato in tempo reale; chiusura della sessione (RF-23).
// Lo stato arriva con Realtime: quando il visore si abbina, la pagina cambia da sola.
import { useEffect, useRef, useState } from 'react'
import { Link, useLocation, useNavigate, useParams } from 'react-router'
import { useAuth } from '../../lib/auth-context'
import { supabase } from '../../lib/supabase'
import { VistaDalVivo } from '../../components/VistaDalVivo'
import { ScaricaReport } from '../../components/ScaricaReport'
import { formatDateTime, formatDuration } from '../../lib/format'
import {
  SESSION_COLUMNS,
  closeSession,
  createPairingCode,
  formatPairingCode,
  loadScenarioNames,
  msUntil,
  statusLabel,
  type SessionRow,
  type SessionStatus,
} from '../../lib/sessions'

type Pairing = { code: string; expiresAt: string } | null

export function Sessione() {
  const { id = '' } = useParams()
  // Codice e chiusura sono del formatore della sessione: l'amministratore consulta soltanto (RF-22).
  const auth = useAuth()
  const isTrainer = auth.status === 'signed_in' && auth.profile.role === 'trainer'
  const location = useLocation()
  const navigate = useNavigate()
  const [session, setSession] = useState<SessionRow | null | undefined>(undefined)
  const [scenarioName, setScenarioName] = useState<string>('')
  const [pairing, setPairing] = useState<Pairing>(null)
  const [pairingError, setPairingError] = useState<string | null>(null)
  const [generating, setGenerating] = useState(false)
  const autoGenerated = useRef(false)

  // Lettura iniziale e aggiornamenti di stato in tempo reale.
  useEffect(() => {
    let current = true
    void Promise.all([
      supabase.from('sessions').select(SESSION_COLUMNS).eq('id', id).maybeSingle(),
      loadScenarioNames(),
    ]).then(([res, names]) => {
      if (!current) return
      const row = res.data as SessionRow | null
      setSession(row)
      if (row) setScenarioName(names.get(row.scenario_id) ?? row.scenario_id)
    })

    const channel = supabase
      .channel(`sessione-${id}`)
      .on(
        'postgres_changes',
        { event: 'UPDATE', schema: 'public', table: 'sessions', filter: `id=eq.${id}` },
        (payload) => {
          const next = payload.new as { status: SessionStatus; started_at: string | null; closed_at: string | null }
          setSession((s) => (s ? { ...s, ...next } : s))
          if (next.status !== 'waiting') setPairing(null)
        },
      )
      .subscribe()

    return () => {
      current = false
      void supabase.removeChannel(channel)
    }
  }, [id])

  async function generate() {
    setGenerating(true)
    setPairingError(null)
    const result = await createPairingCode(id)
    setGenerating(false)
    if (result.ok) setPairing({ code: result.code, expiresAt: result.expiresAt })
    else setPairingError(result.message)
  }

  // Appena creata la sessione il codice si genera da solo (una volta sola, anche ricaricando).
  useEffect(() => {
    const isNew = (location.state as { nuova?: boolean } | null)?.nuova
    if (!isNew || session?.status !== 'waiting' || autoGenerated.current) return
    autoGenerated.current = true
    navigate(location.pathname, { replace: true, state: null })
    void createPairingCode(id).then((result) => {
      if (result.ok) setPairing({ code: result.code, expiresAt: result.expiresAt })
      else setPairingError(result.message)
    })
  }, [id, location.pathname, location.state, navigate, session?.status])

  if (session === undefined) return <p className="muted">Caricamento…</p>
  if (session === null) {
    return (
      <section className="carta vuoto">
        <h1>Sessione non trovata</h1>
        <p>Non esiste, oppure appartiene a un altro formatore.</p>
        <Link className="btn btn-secondario" to="/">
          Torna alle sessioni
        </Link>
      </section>
    )
  }

  const code = session.participant?.participant_code ?? 'studente spostato'

  return (
    <>
      <div className="pagina-testa">
        <div>
          <p className="sopratitolo">
            <span className={`esito ${statusClass(session.status)}`}>{statusLabel(session.status)}</span>
          </p>
          <h1>
            Sessione di{" "}
            <Link className="codice link-codice" to={`/studenti/${session.participant_id}`}>
              {code}
            </Link>
          </h1>
          <p>
            {scenarioName}. Creata il {formatDateTime(session.created_at)}.
          </p>
        </div>
        <div className="azioni-pagina">
          {session.status !== 'waiting' && (
            <ScaricaReport
              sessionId={session.id}
              session={{
                participantCode: code,
                scenarioName,
                status: session.status,
                createdAt: session.created_at,
                startedAt: session.started_at,
                closedAt: session.closed_at,
              }}
            />
          )}
          {isTrainer && session.status !== 'closed' && <ChiudiSessione sessionId={session.id} />}
        </div>
      </div>

      {!isTrainer && session.status === 'waiting' && (
        <section className="carta vuoto">
          <h2>In attesa del visore</h2>
          <p>Il codice di abbinamento lo vede solo il formatore della sessione.</p>
        </section>
      )}

      {isTrainer && session.status === 'waiting' && (
        <CodiceAbbinamento
          pairing={pairing}
          error={pairingError}
          generating={generating}
          onGenerate={() => void generate()}
        />
      )}

      {session.status === 'closed' && (
        <div className="avviso">
          Sessione chiusa il {session.closed_at ? formatDateTime(session.closed_at) : '—'}: il visore non può più inviare
          dati.
        </div>
      )}

      {session.status !== 'waiting' && (
        <VistaDalVivo sessionId={session.id} scenarioId={session.scenario_id} scenarioName={scenarioName} />
      )}
    </>
  )
}

function statusClass(status: SessionStatus): string {
  return status === 'active' ? 'esito-attivo' : 'esito-neutro'
}

function CodiceAbbinamento({
  pairing,
  error,
  generating,
  onGenerate,
}: {
  pairing: Pairing
  error: string | null
  generating: boolean
  onGenerate: () => void
}) {
  const [now, setNow] = useState(() => Date.now())

  useEffect(() => {
    if (!pairing) return
    const timer = setInterval(() => setNow(Date.now()), 1000)
    return () => clearInterval(timer)
  }, [pairing])

  const left = pairing ? msUntil(pairing.expiresAt, now) : 0
  const expired = pairing !== null && left === 0

  return (
    <section className="carta abbinamento" aria-live="polite">
      <div className="abbinamento-testo">
        <h2>Codice per il visore</h2>
        <p className="muted">
          All'avvio del visore lo studente inserisce queste 6 cifre. Il codice vale 10 minuti e una sola volta; quando
          il visore si collega questa pagina si aggiorna da sola.
        </p>
      </div>

      {pairing && !expired ? (
        <div className="abbinamento-codice">
          <p className="codice codice-grande" aria-label={`Codice ${pairing.code.split('').join(' ')}`}>
            {formatPairingCode(pairing.code)}
          </p>
          <p className="muted num">Scade tra {formatDuration(left)}</p>
        </div>
      ) : (
        <div className="abbinamento-codice">
          <p className="abbinamento-vuoto">
            {expired ? 'Codice scaduto: generane uno nuovo.' : generating ? 'Generazione del codice…' : 'Nessun codice attivo.'}
          </p>
        </div>
      )}

      <div className="abbinamento-azioni">
        <button
          className={`btn ${pairing && !expired ? 'btn-secondario' : 'btn-primario'}`}
          type="button"
          onClick={onGenerate}
          disabled={generating}
        >
          {pairing && !expired ? 'Genera un nuovo codice' : 'Genera il codice'}
        </button>
        {error && (
          <p className="stato-modulo errore" role="alert">
            {error}
          </p>
        )}
      </div>
    </section>
  )
}

function ChiudiSessione({ sessionId }: { sessionId: string }) {
  const [confirming, setConfirming] = useState(false)
  const [error, setError] = useState(false)

  async function close() {
    setError(false)
    if (!(await closeSession(sessionId))) setError(true)
    // Lo stato "chiusa" arriva con Realtime.
  }

  if (!confirming) {
    return (
      <button className="btn btn-pericolo" type="button" onClick={() => setConfirming(true)}>
        Chiudi sessione
      </button>
    )
  }
  return (
    <div className="conferma" role="group" aria-label="Conferma chiusura">
      <span>Una sessione chiusa non si riapre.</span>
      <button className="btn btn-pericolo" type="button" onClick={() => void close()}>
        Chiudi definitivamente
      </button>
      <button className="btn btn-secondario" type="button" onClick={() => setConfirming(false)}>
        Annulla
      </button>
      {error && (
        <span className="errore-campo" role="alert">
          Chiusura non riuscita, riprova.
        </span>
      )}
    </div>
  )
}
